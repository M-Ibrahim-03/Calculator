

// Functions for each basic calculator function

// Adding two numbers
function add(a, b) {
    return a+b;
}

// Subtracting two numbers
function subtract(a, b) {
    return a-b;
}

// Multiply two numbers
function multiply(a, b) {
    return a*b;
}

// Divide two numbers
function divide(a, b) {
    return a/b;
}